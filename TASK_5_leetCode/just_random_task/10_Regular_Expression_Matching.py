# Компании
# Для входной строки s и шаблона p реализуйте сопоставление с регулярным выражением с поддержкой '.' и '*' где:

# '.'Соответствует любому отдельному символу.​​​​
# '*'Соответствует нулю или более предшествующих элементов.
# Возвращает логическое значение, указывающее, охватывает ли совпадение всю входную строку (а не ее часть).

 

# Пример 1:

# Входные данные: s = "aa", p = "a"
# Выходные данные: false
# Пояснение: "a" не соответствует всей строке "aa".
# Пример 2:

# Входные данные: s = "aa", p = "a*".
# Выходные данные: true
# Пояснение: '*' означает ноль или более вхождений предыдущего элемента 'a'. Таким образом, при однократном повторении 'a' получается "aa".
# Пример 3:

# Входные данные: s = "ab", p = ".*"
# Выходные данные: true
# Пояснение: ".*" означает "ноль или более (*) любых символов (.)".
 

# Ограничения:

# 1 <= s.length <= 20
# 1 <= p.length <= 20
# sсодержит только строчные буквы английского алфавита.
# p содержит только строчные буквы английского алфавита, '.', и '*'.
# Гарантируется, что перед каждым вхождением символа '*' будет предшествующий допустимый символ.
 
