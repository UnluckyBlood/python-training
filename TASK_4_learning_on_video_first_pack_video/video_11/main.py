# Замороженное множество frozen set, объединение кортежа и множества, создаётся множество и нельзя изменять ни одно множество

new_data = frozenset([5, 7, 3, 5, 5, '32', True, 4, 6])
print(new_data)
# new_data.add(4) нельзя добавлять так как кортеж, получается что все элементы в хаотичном порядке, не имеют дубликатов, и нельзя изменить их